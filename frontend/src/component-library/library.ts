/*
 * Component library. Symbols follow IEC 60617 conventions in simplified form.
 * Electronic symbols are drawn on a 2.5 mm grid; installation plan symbols are
 * drawn at plan scale (hundreds of millimetres) so they read correctly on 1:50 / 1:100 plans.
 */

const W = 0.25; // default stroke width (mm)
const num = (v: PropertyValue | undefined, d = 0): number => (typeof v === 'number' ? v : typeof v === 'string' ? parseFloat(v) || d : d);

const pin = (id: string, name: string, x: number, y: number, kind: PinDef['kind'] = 'passive'): PinDef => ({ id, name, x, y, kind });
const p = (key: string, label: string, def: PropertyValue, extra: Partial<PropertyDef> = {}): PropertyDef => ({
  key,
  label,
  kind: typeof def === 'number' ? 'number' : typeof def === 'boolean' ? 'boolean' : 'string',
  default: def,
  ...extra,
});

// ---------- symbol helpers ----------
function arrowHead(x: number, y: number, angleDeg: number, size = 1): Primitive {
  const a = (angleDeg * Math.PI) / 180;
  const l = { x: x - size * Math.cos(a - 0.45), y: y - size * Math.sin(a - 0.45) };
  const r = { x: x - size * Math.cos(a + 0.45), y: y - size * Math.sin(a + 0.45) };
  return { k: 'poly', pts: [l, { x, y }, r], closed: true, fill: true, w: W };
}

function leads2(len = 5, inner = 3): Primitive[] {
  return [line(-len, 0, -inner, 0, W), line(inner, 0, len, 0, W)];
}
function vleads(len = 5, inner = 3): Primitive[] {
  return [line(0, -len, 0, -inner, W), line(0, inner, 0, len, W)];
}

function diodeBody(): Primitive[] {
  return [
    ...leads2(5, 1.5),
    { k: 'poly', pts: [{ x: -1.5, y: -1.75 }, { x: 1.5, y: 0 }, { x: -1.5, y: 1.75 }], closed: true, w: W },
    line(1.5, -1.75, 1.5, 1.75, W),
  ];
}

function contactSymbol(nc: boolean, actuator: 'none' | 'push' | 'estop' | 'limit' | 'thermal'): Primitive[] {
  const prims: Primitive[] = [line(0, -5, 0, -2, W), line(0, 2, 0, 5, W)];
  // movable contact
  prims.push(line(0, 2, -1.8, -2.2, W));
  if (nc) prims.push(line(0, -2, -2.2, -2, W));
  if (actuator === 'push') prims.push(line(-0.9, 0, -4, 0, W), line(-4, -1, -4, 1, W));
  if (actuator === 'estop') prims.push(line(-0.9, 0, -4, 0, W), { k: 'arc', c: { x: -5.2, y: 0 }, r: 1.2, a0: 90, a1: 270, w: W });
  if (actuator === 'limit') prims.push(line(-0.9, 0, -3.5, 0, W), { k: 'poly', pts: [{ x: -3.5, y: -1 }, { x: -4.6, y: 0 }, { x: -3.5, y: 1 }], w: W });
  if (actuator === 'thermal') prims.push(line(-0.9, 0, -2.4, 0, W), { k: 'poly', pts: [{ x: -2.4, y: 0 }, { x: -2.4, y: -1 }, { x: -3.4, y: -1 }, { x: -3.4, y: 1 }, { x: -4.4, y: 1 }, { x: -4.4, y: 0 }], w: W });
  return prims;
}

