export const LIBRARY: Record<string, ComponentDef> = Object.fromEntries(defs.map((d) => [d.type, d]));
export const LIBRARY_LIST: ComponentDef[] = defs;

export function getDef(type: string): ComponentDef {
  const d = LIBRARY[type];
  if (!d) throw new Error(`Unknown component type "${type}"`);
  return d;
}

export function defaultProperties(type: string): Record<string, PropertyValue> {
  const out: Record<string, PropertyValue> = {};
  for (const pd of getDef(type).properties) out[pd.key] = pd.default;
  if (type === 'led') out.vf = ledTypicalVf[String(out.color)] ?? 2;
  return out;
}

